/* -- Framebuffer state ----------------------------------------------------- */
int fb_available = 0;
static int s_fb_locked = 0;  /* 1 = compositor owns FB, suppress text output */
/* Leaf lock: printk/TTY/scheduler locks may precede this lock, never the
 * reverse. No allocation, logging, callbacks or user-memory access while held.
 * IRQ-save is required: console output can also arrive from interrupt context.
 * fb_init publishes immutable geometry once, before concurrent console use.
 * Panic rendering deliberately bypasses this lock (the fault may hold it). */
static spinlock_t s_text_lock = SPINLOCK_INIT;
/* Emergency takeover cannot wait for s_text_lock: a fault can hold it.
 * Stop new normal drawing without changing compositor ownership. An already
 * active writer on another CPU may finish; panic output is best-effort. */
static int s_panic_active;

static volatile uint32_t *s_fb_va    = (void *)0;
/* Shadow buffer: normal WB-cached DRAM copy of the framebuffer.
 * All pixel writes go to both s_shadow and s_fb_va.
 * _fb_scroll reads from s_shadow (fast cacheable read), then blits
 * the whole screen to s_fb_va as sequential WC writes (fast write-combining).
 * This avoids uncached reads from WC framebuffer memory during scroll,
 * which is the same strategy Linux vesafb/efifb uses. */
static uint32_t          *s_shadow   = (void *)0;
static uint32_t           s_pitch_px = 0;
static uint32_t           s_cols     = 0;
static uint32_t           s_rows     = 0;
static uint32_t           s_col      = 0;
static uint32_t           s_row      = 0;
static uint64_t           s_fb_pixels = 0; /* pitch/4 * actual mapped height */

/* Physical address and dimensions — immutable after fb_init, for sys_fb_map.
 * s_cols/s_rows are the complete 8x16 cells inside these pixel dimensions;
 * no text operation may use the page-rounded allocation as extra screen. */
static uint64_t s_fb_phys;
static uint32_t s_fb_width;
static uint32_t s_fb_height;
static uint32_t s_fb_pitch;

/* ANSI CSI escape-sequence state machine.
 * Handles the two sequences emitted by /bin/clear: \033[2J and \033[H. */
static int  s_esc_state = 0;    /* 0=normal 1=saw_ESC 2=in_CSI */
static char s_esc_buf[16];
static int  s_esc_len   = 0;
static int  s_esc_overflow = 0; /* discard, never execute a truncated sequence */

#define FB_FG  0x00FFFFFFu
#define FB_BG  0x00000000u

/* FB_MAX_WIDTH / FB_MAX_HEIGHT / FB_MAX_PITCH now live in fb.h so that the
 * boot-tag parser in kernel/arch/x86_64/arch_mm.c can sanitise the geometry
 * at the source using the identical limits (defense in depth). */

/* Shared bounds for glyphs AND cursor overlays. Use wide offsets and check
 * the last pixel against the actual pitch*height extent, not mapped padding.
 * Internal callers hold s_text_lock; coordinates can never escape a cell. */
static int
_fb_cell_base(uint32_t row, uint32_t col, uint64_t *base)
{
    if (!s_fb_va || row >= s_rows || col >= s_cols)
        return 0;
    *base = (uint64_t)row * 16u * s_pitch_px + (uint64_t)col * 8u;
    return *base + 15u * (uint64_t)s_pitch_px + 8u <= s_fb_pixels;
}

static void
_fb_draw_char(uint32_t row, uint32_t col, char c)
{
    uint64_t base_px;
    if (!_fb_cell_base(row, col, &base_px))
        return;
    const uint8_t *glyph = s_font + ((uint8_t)c) * 16u;
    uint32_t y, x;
    for (y = 0; y < 16u; y++) {
        uint8_t bits = glyph[y];
        for (x = 0; x < 8u; x++) {
            uint32_t color = (bits & (0x80u >> x)) ? FB_FG : FB_BG;
            uint64_t idx  = base_px + y * s_pitch_px + x;
            if (s_shadow) s_shadow[idx] = color;
            s_fb_va[idx] = color;
        }
    }
}

static void
_fb_scroll(void)
{
    if (!s_rows || !s_cols)
        return;
    uint64_t row_pixels = 16u * (uint64_t)s_pitch_px;
    uint64_t total      = (s_rows - 1u) * row_pixels;

    if (s_shadow) {
        /* Fast path: shift shadow in DRAM (WB-cached, fast reads),
         * then blit the whole screen to the WC framebuffer as a single
         * sequential write stream (write-combined, fast).
         * FB_BG == 0x00000000, so memset-zero clears the last text row. */
        __builtin_memmove(s_shadow, s_shadow + row_pixels,
                          total * sizeof(uint32_t));
        __builtin_memset(s_shadow + (s_rows - 1u) * row_pixels, 0,
                         row_pixels * sizeof(uint32_t));
        /* Cast away volatile: we want REP MOVSQ batched WC writes, not
         * per-element volatile stores which prevent write-combining. */
        __builtin_memmove((uint32_t *)s_fb_va, s_shadow,
                          s_rows * row_pixels * sizeof(uint32_t));
    } else {
        /* Slow fallback (no shadow): scalar loop over WC reads */
        uint64_t i;
        for (i = 0; i < total; i++)
            s_fb_va[i] = s_fb_va[i + row_pixels];
        for (i = 0; i < row_pixels; i++)
            s_fb_va[(s_rows - 1u) * row_pixels + i] = FB_BG;
    }
    s_row = s_rows - 1u;
}

int
fb_get_phys_info(uint64_t *phys_out, uint32_t *width_out,
                 uint32_t *height_out, uint32_t *pitch_out)
{
    if (!fb_available || s_fb_phys == 0)
        return 0;
    *phys_out  = s_fb_phys;
    *width_out = s_fb_width;
    *height_out = s_fb_height;
    *pitch_out = s_fb_pitch;
    return 1;
}

void
fb_init(void)
{
    arch_fb_info_t info;
    uint32_t fb_pages;
    uint8_t *region;

    if (!arch_get_fb_info(&info))
        return;

    /* Validate the boot-tag geometry before trusting it in any size math.
     * arch_mm.c already sanitises the same geometry at the parse site
     * (defense in depth, shared FB_MAX_* limits in fb.h) and refuses to
     * store an out-of-range tag, but we re-check here so this layer never
     * silently relies on the source enforcing it: reject implausible or
     * degenerate dimensions so the page-count and clear extents below
     * cannot wrap.  bpp is guaranteed 32 by arch_get_fb_info, hence pitch
     * must hold at least width*4 bytes per scanline. */
    if (info.width  == 0 || info.width  > FB_MAX_WIDTH  ||
        info.height == 0 || info.height > FB_MAX_HEIGHT ||
        info.pitch  == 0 || info.pitch  > FB_MAX_PITCH  ||
        (info.pitch & 3u) != 0 ||
        info.pitch < (uint64_t)info.width * 4u) {
        serial_write_string("[FB] WARN: implausible framebuffer geometry, "
                            "ignoring\n");
        return;
    }

    /* Compute the byte extent in 64-bit: info.pitch * info.height can
     * exceed UINT32_MAX for large modes, so the multiply must not be a
     * 32-bit one. With the bounds above this maxes at 1 GiB. */
    {
        uint64_t fb_bytes = (uint64_t)info.pitch * (uint64_t)info.height;
        fb_pages = (uint32_t)((fb_bytes + 0xFFFu) / 0x1000u);
    }
    region = (uint8_t *)kva_map_mmio(info.addr, fb_pages);
    if (!region) {
        serial_write_string("[FB] WARN: kva alloc failed\n");
        return;
    }

    s_fb_va    = (volatile uint32_t *)region;
    s_pitch_px = info.pitch / 4u;
    s_cols     = info.width  / 8u;
    s_rows     = info.height / 16u;
    s_fb_pixels = (uint64_t)s_pitch_px * info.height;

    /* Save physical info for sys_fb_map */
    s_fb_phys   = info.addr;
    s_fb_width  = info.width;
    s_fb_height = info.height;
    s_fb_pitch  = info.pitch;
    s_col      = 0;
    s_row      = 0;

    /* Allocate shadow buffer: same size as framebuffer, backed by normal
     * WB-cached PMM pages (no remapping needed — kva_alloc_pages uses WB). */
    {
        uint8_t *shbuf = (uint8_t *)kva_alloc_pages((uint64_t)fb_pages);
        if (shbuf)
            s_shadow = (uint32_t *)shbuf;
        /* Shadow allocation failure is non-fatal; scroll falls back to
         * the slow scalar loop. */
    }

    {
        /* 64-bit extent: s_pitch_px * info.height can exceed UINT32_MAX,
         * which would wrap a 32-bit product and either under-clear (leaving
         * boot garbage) or, paired with a wrapped page-count, over-clear
         * past the mapped FB.  Geometry is bounded above, so this is exact. */
        uint64_t total_px = (uint64_t)s_pitch_px * (uint64_t)info.height;
        /* FB_BG == 0x00000000; memset-zero clears to black.
         * Cast away volatile for batched write-combined writes. */
        __builtin_memset((uint32_t *)s_fb_va, 0, total_px * sizeof(uint32_t));
        /* Zero the shadow too.  Without this, gutter pixels (right of the last
         * character column, between s_cols*8 and s_pitch_px) are PMM garbage.
         * On the first _fb_scroll those garbage pixels are blitted to the FB,
         * causing "TV static" on the right side of the screen.
         *
         * SAFETY: the multiboot2 info structure is reserved in PMM via
         * arch_mm.c x86_reserved[1] (set at arch_mm_init time), so
         * kva_alloc_pages cannot return a page that overlaps the RSDP. */
        if (s_shadow)
            __builtin_memset(s_shadow, 0, total_px * sizeof(uint32_t));
    }

    fb_available = 1;
    printk("[FB] OK: %ux%ux%u\n", info.width, info.height, (uint32_t)info.bpp);
}

static void
_fb_clear_screen(void)
{
    /* 64-bit extent: s_pitch_px * (s_rows*16) can exceed UINT32_MAX on
     * large modes; a wrapped 32-bit product would over- or under-clear. */
    uint64_t total_px = (uint64_t)s_pitch_px * (uint64_t)s_rows * 16u;
    __builtin_memset((uint32_t *)s_fb_va, 0, total_px * sizeof(uint32_t));
    if (s_shadow)
        __builtin_memset(s_shadow, 0, total_px * sizeof(uint32_t));
    s_row = 0;
    s_col = 0;
}

/* Parse decimal parameters without wraparound. No terminal coordinate or
 * relative movement needs to exceed the maximum supported pixel dimension. */
static uint32_t
_fb_csi_number(int *pos)
{
    uint32_t n = 0;
    while (*pos < s_esc_len &&
           s_esc_buf[*pos] >= '0' && s_esc_buf[*pos] <= '9') {
        n = n * 10u + (uint32_t)(s_esc_buf[(*pos)++] - '0');
        if (n > FB_MAX_WIDTH)
            n = FB_MAX_WIDTH;
    }
    return n;
}

/* _fb_dispatch_csi — called when a CSI sequence final-byte is received.
 * s_esc_buf[0..s_esc_len-1] holds the parameter string; cmd is the
 * final byte ('J', 'H', 'K', …). */
static void
_fb_dispatch_csi(char cmd)
{
    if (cmd == 'J') {
        /* Erase in display.  Only param=2 (whole screen) is handled. */
        if (s_esc_len == 1 && s_esc_buf[0] == '2')
            _fb_clear_screen();
        /* params 0, 1, or anything else: no-op for now */
    } else if (cmd == 'H' || cmd == 'f') {
        /* Cursor position: \033[row;colH (1-indexed, defaults to 1). */
        uint32_t row = 0, col = 0;
        int i = 0;
        row = _fb_csi_number(&i);
        if (row > 0) row--;
        if (i < s_esc_len && s_esc_buf[i] == ';') {
            i++;
            col = _fb_csi_number(&i);
            if (col > 0) col--;
        }
        if (i != s_esc_len)
            return;
        s_row = (row < s_rows) ? row : s_rows - 1u;
        s_col = (col < s_cols) ? col : s_cols - 1u;
    } else if (cmd == 'K') {
        /* Erase in line.  param=0 (default): clear from cursor to EOL. */
        if (s_esc_len && !(s_esc_len == 1 && s_esc_buf[0] == '0'))
            return;
        uint32_t c;
        for (c = s_col; c < s_cols; c++)
            _fb_draw_char(s_row, c, ' ');
    } else if (cmd == 'C' || cmd == 'D') {
        /* Relative movement, default/zero n=1. Reject non-numeric params. */
        int i = 0;
        uint32_t n = _fb_csi_number(&i);
        if (i != s_esc_len)
            return;
        if (!n) n = 1;
        if (cmd == 'C')
            s_col += (n < s_cols - s_col) ? n : s_cols - 1u - s_col;
        else
            s_col = (n > s_col) ? 0 : s_col - n;
    }
    /* Other sequences are silently ignored. */
}

/* Software text cursor — underline bar at current position */
static int s_cursor_drawn;

static void
_fb_draw_cursor(void)
{
    if (s_cursor_drawn || s_fb_locked) return;
    uint64_t base;
    if (!_fb_cell_base(s_row, s_col, &base))
        return;
    /* Draw underline on last 2 scanlines of the cell */
    for (uint32_t y = 14; y < 16; y++)
        for (uint32_t x = 0; x < 8; x++) {
            uint64_t idx = base + y * s_pitch_px + x;
            if (s_shadow) s_shadow[idx] = FB_FG;
            s_fb_va[idx] = FB_FG;
        }
    s_cursor_drawn = 1;
}

static void
_fb_erase_cursor(void)
{
    if (!s_cursor_drawn) return;
    s_cursor_drawn = 0;
    /* Redraw the character cell at cursor position to erase the underline */
    uint64_t base;
    if (!_fb_cell_base(s_row, s_col, &base))
        return;
    for (uint32_t y = 14; y < 16; y++)
        for (uint32_t x = 0; x < 8; x++) {
            uint64_t idx = base + y * s_pitch_px + x;
            if (s_shadow) s_shadow[idx] = FB_BG;
            s_fb_va[idx] = FB_BG;
        }
}

/* All helpers below run under s_text_lock, including escape/control paths,
 * cursor erase/draw and scrolling. No writer can observe the transient
 * s_row == s_rows between a bottom-row newline/wrap and the scroll. */
static void
_fb_newline(void)
{
    s_col = 0;
    if (++s_row >= s_rows)
        _fb_scroll();
}

static void
_fb_put_glyph(char c)
{
    _fb_draw_char(s_row, s_col, c);
    if (++s_col >= s_cols)
        _fb_newline();
}

static void
_fb_putchar_locked(char c)
{
    if (!fb_available || s_fb_locked ||
        __atomic_load_n(&s_panic_active, __ATOMIC_ACQUIRE) ||
        !s_cols || !s_rows) return;
    _fb_erase_cursor();

    /* ANSI CSI state machine */
    if (c == '\033') {
        s_esc_state = 1;
        _fb_draw_cursor();
        return;
    }
    if (c == '\030' || c == '\032') { /* CAN/SUB cancel a partial sequence */
        s_esc_state = 0;
        _fb_draw_cursor();
        return;
    }
    if (s_esc_state == 1) {
        if (c == '[') {
            s_esc_state = 2;
            s_esc_len   = 0;
            s_esc_overflow = 0;
        } else {
            s_esc_state = 0;
        }
        _fb_draw_cursor();
        return;
    }
    if (s_esc_state == 2) {
        if ((c >= '0' && c <= '9') || c == ';') {
            if (s_esc_len < 15)
                s_esc_buf[s_esc_len++] = c;
            else
                s_esc_overflow = 1;
            _fb_draw_cursor();
            return;
        }
        s_esc_state     = 0;
        s_esc_buf[s_esc_len] = '\0';
        if (!s_esc_overflow)
            _fb_dispatch_csi(c);
        _fb_draw_cursor();
        return;
    }

    if (c == '\n') {
        _fb_newline();
    } else if (c == '\r') {
        s_col = 0;
    } else if (c == '\b') {
        if (s_col > 0) {
            s_col--;
            _fb_draw_char(s_row, s_col, ' ');
        }
    } else if (c == '\t') {
        uint32_t spaces = 8u - (s_col & 7u);
        while (spaces--)
            _fb_put_glyph(' ');
    } else if ((uint8_t)c >= 0x20u && c != '\177') {
        _fb_put_glyph(c);
    }

    _fb_draw_cursor();
}

void
fb_putchar(char c)
{
    irqflags_t flags = spin_lock_irqsave(&s_text_lock);
    _fb_putchar_locked(c);
    spin_unlock_irqrestore(&s_text_lock, flags);
}

void
fb_write_string(const char *s)
{
    while (*s)
        fb_putchar(*s++);
}

void
fb_lock_compositor(void)
{
    irqflags_t flags = spin_lock_irqsave(&s_text_lock);
    _fb_erase_cursor();
    s_fb_locked = 1;
    spin_unlock_irqrestore(&s_text_lock, flags);
}

void
fb_heartbeat(void)
{
    irqflags_t flags = spin_lock_irqsave(&s_text_lock);
    if (!fb_available || s_fb_locked ||
        __atomic_load_n(&s_panic_active, __ATOMIC_ACQUIRE) ||
        !s_fb_va || !s_pitch_px)
        goto out;
    /* Toggle a 4x4 block in the top-left corner between green and black.
     * Called from sched_tick (~100Hz). Visible change every ~50 ticks. */
    static uint32_t counter = 0;
    counter++;
    uint32_t color = (counter & 64) ? 0x0000FF00u : 0x00003300u;
    uint32_t y, x;
    for (y = 0; y < 4 && y < s_fb_height; y++)
        for (x = 0; x < 4 && x < s_fb_width; x++)
            s_fb_va[y * s_pitch_px + x] = color;
out:
    spin_unlock_irqrestore(&s_text_lock, flags);
}

#ifdef __x86_64__
void
fb_check_amd(void)
{
    const pcie_device_t *amd;

    if (fb_available)
        return;   /* framebuffer already working — nothing to report */

    /* Note: pcie_find_device returns the first class-0x03 device.
     * On multi-GPU systems this may not be the AMD GPU if another
     * display controller appears first in the PCIe table. Single-iGPU
     * systems (the target platform) are always correct. */
    amd = pcie_find_device(0x03u, 0xFFu, 0xFFu);
    if (amd == NULL || amd->vendor_id != 0x1002u)
        return;   /* no AMD display device — silent */

    printk("[FB] WARN: AMD GPU 0x%x found but no framebuffer tag from GRUB\n",
           (uint32_t)amd->device_id);
    printk("[FB] WARN: ensure GRUB boots in UEFI mode (AMD APUs lack VBE)\n");
}
#endif /* __x86_64__ */

