typedef struct {
    uint32_t h[5];
    uint64_t bytes;
    uint8_t buf[64];
    size_t used;
} sha1_ctx_t;

static void wipe(void *p,size_t n)
{ volatile uint8_t *v=p;while(n--)*v++=0; }

static uint32_t rol(uint32_t x, unsigned n) { return (x << n) | (x >> (32 - n)); }

static void sha1_block(sha1_ctx_t *c, const uint8_t b[64])
{
    uint32_t w[80], a, d, e, f, k, t, bb, cc;
    for (int i = 0; i < 16; i++)
        w[i] = ((uint32_t)b[i*4] << 24) | ((uint32_t)b[i*4+1] << 16) |
               ((uint32_t)b[i*4+2] << 8) | b[i*4+3];
    for (int i = 16; i < 80; i++) w[i] = rol(w[i-3]^w[i-8]^w[i-14]^w[i-16], 1);
    a=c->h[0]; bb=c->h[1]; cc=c->h[2]; d=c->h[3]; e=c->h[4];
    for (int i = 0; i < 80; i++) {
        if (i < 20) { f=(bb&cc)|((~bb)&d); k=0x5a827999; }
        else if (i < 40) { f=bb^cc^d; k=0x6ed9eba1; }
        else if (i < 60) { f=(bb&cc)|(bb&d)|(cc&d); k=0x8f1bbcdc; }
        else { f=bb^cc^d; k=0xca62c1d6; }
        t=rol(a,5)+f+e+k+w[i]; e=d; d=cc; cc=rol(bb,30); bb=a; a=t;
    }
    c->h[0]+=a; c->h[1]+=bb; c->h[2]+=cc; c->h[3]+=d; c->h[4]+=e;
}

static void sha1_init(sha1_ctx_t *c)
{
    c->h[0]=0x67452301; c->h[1]=0xefcdab89; c->h[2]=0x98badcfe;
    c->h[3]=0x10325476; c->h[4]=0xc3d2e1f0; c->bytes=0; c->used=0;
}

static void sha1_update(sha1_ctx_t *c, const void *data, size_t len)
{
    const uint8_t *p=data; c->bytes += len;
    while (len) {
        size_t n=64-c->used; if (n>len) n=len;
        for (size_t i=0;i<n;i++) c->buf[c->used+i]=p[i];
        c->used+=n; p+=n; len-=n;
        if (c->used==64) { sha1_block(c,c->buf); c->used=0; }
    }
}

static void sha1_final(sha1_ctx_t *c, uint8_t out[20])
{
    uint64_t bits=c->bytes*8; c->buf[c->used++]=0x80;
    if (c->used>56) { while(c->used<64)c->buf[c->used++]=0; sha1_block(c,c->buf); c->used=0; }
    while(c->used<56)c->buf[c->used++]=0;
    for(int i=7;i>=0;i--)c->buf[c->used++]=(uint8_t)(bits>>(i*8));
    sha1_block(c,c->buf);
    for(int i=0;i<5;i++){out[i*4]=c->h[i]>>24;out[i*4+1]=c->h[i]>>16;out[i*4+2]=c->h[i]>>8;out[i*4+3]=c->h[i];}
}

static void hmac_sha1(const uint8_t *key,size_t klen,const uint8_t *data,size_t len,uint8_t out[20])
{
    uint8_t k[64]={0}, inner[20]; sha1_ctx_t c;
    if(klen>64){sha1_init(&c);sha1_update(&c,key,klen);sha1_final(&c,k);klen=20;}
    else for(size_t i=0;i<klen;i++)k[i]=key[i];
    for(int i=0;i<64;i++)k[i]^=0x36;
    sha1_init(&c);sha1_update(&c,k,64);sha1_update(&c,data,len);sha1_final(&c,inner);
    for(int i=0;i<64;i++)k[i]^=0x36^0x5c;
    sha1_init(&c);sha1_update(&c,k,64);sha1_update(&c,inner,20);sha1_final(&c,out);
    wipe(k,sizeof(k));wipe(inner,sizeof(inner));wipe(&c,sizeof(c));
}

void wpa2_pmk(const uint8_t *pass,size_t plen,const uint8_t *ssid,size_t slen,uint8_t pmk[32])
{
    uint8_t msg[36],u[20],t[20];
    for(int block=1,off=0;off<32;block++,off+=20){
        for(size_t i=0;i<slen;i++)msg[i]=ssid[i];
        msg[slen]=0;msg[slen+1]=0;msg[slen+2]=0;msg[slen+3]=(uint8_t)block;
        hmac_sha1(pass,plen,msg,slen+4,u); for(int i=0;i<20;i++)t[i]=u[i];
        for(int n=1;n<4096;n++){hmac_sha1(pass,plen,u,20,u);for(int i=0;i<20;i++)t[i]^=u[i];}
        int take=32-off<20?32-off:20;for(int i=0;i<take;i++)pmk[off+i]=t[i];
    }
    wipe(msg,sizeof(msg));wipe(u,sizeof(u));wipe(t,sizeof(t));
}

static int bytes_cmp(const uint8_t *a,const uint8_t *b,size_t n)
{ for(size_t i=0;i<n;i++)if(a[i]!=b[i])return a[i]<b[i]?-1:1;return 0; }

void wpa2_ptk(const uint8_t pmk[32],const uint8_t aa[6],const uint8_t spa[6],
              const uint8_t an[32],const uint8_t sn[32],uint8_t ptk[64])
{
    static const uint8_t label[]="Pairwise key expansion";
    uint8_t data[100],digest[20]; size_t p=0;
    for(size_t i=0;i<sizeof(label)-1;i++)data[p++]=label[i];
    data[p++]=0;
    const uint8_t *m1=bytes_cmp(aa,spa,6)<0?aa:spa,*m2=m1==aa?spa:aa;
    const uint8_t *n1=bytes_cmp(an,sn,32)<0?an:sn,*n2=n1==an?sn:an;
    for(int i=0;i<6;i++)data[p++]=m1[i];
    for(int i=0;i<6;i++)data[p++]=m2[i];
    for(int i=0;i<32;i++)data[p++]=n1[i];
    for(int i=0;i<32;i++)data[p++]=n2[i];
    for(int off=0,counter=0;off<64;off+=20,counter++){
        data[p]=(uint8_t)counter;hmac_sha1(pmk,32,data,p+1,digest);
        int take=64-off<20?64-off:20;for(int i=0;i<take;i++)ptk[off+i]=digest[i];
    }
    wipe(data,sizeof(data));wipe(digest,sizeof(digest));
}

